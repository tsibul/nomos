def interface_lang(lang):
    """Язык, на котором выйдут строки интерфейса для страницы на языке lang."""
    return lang if lang in UI_LANGS else BASE_LANG


def text(key, lang):
    """Строка интерфейса на языке lang; нет перевода — по-русски."""
    variants = STRINGS[key]
    return variants.get(lang) or variants[BASE_LANG]


def strings_for(lang):
    """Все строки на языке lang — для шаблонов (`{{ t.toc }}`)."""
    return {key: text(key, lang) for key in STRINGS}


def kind_name(act, lang):
    """Вид акта на языке lang; нет перевода — русское название из модели."""
    return KIND_NAMES.get(lang, {}).get(act.kind) or act.get_kind_display()
