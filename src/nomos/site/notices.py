def disclaimer(jurisdiction=None):
    """Отказ в подвале: у актов ЕС — Официальный журнал ЕС, иначе — Официальная газета Кипра."""
    if jurisdiction == 'eu':
        return DISCLAIMER_EU
    return DISCLAIMER_PUBLIC if access.is_restricted() else DISCLAIMER


